        "0.00 to 0.99 paired SE. `FINDINGS_DETERMINISM_2026_09_02.md`",
        "At $k_v=30$ the paired per-seed differences are -0.00009 +/- 0.00034, -0.00040 +/-",
        "0.00008 and -0.00005 +/- 0.00021: **one seed of three separates**, two are",
