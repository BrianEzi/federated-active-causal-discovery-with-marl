    out += ["| $\\rho$ | learned | myopic | paired $\\Delta$ | seed SE | ahead beyond 2 SE |",
            "|---|---|---|---|---|---|"]
    for r in RATES:
        cells = [grid[(r, s)] for s in (0, 1, 2)]
        dl = np.array([c["paired"]["learned-greedy"]["delta"] for c in cells])
