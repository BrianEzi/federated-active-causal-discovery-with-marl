RATES = [1.00, 0.95, 0.90, 0.85, 0.80, 0.70, 0.50]
WIN_AT_OR_BELOW = 0.90
grid = {}
for r in RATES:
    for s in (0, 1, 2):
        p = TR / "power" / f"xfer_rho{r:.2f}_s{s}.json"
        if p.exists():
            d = json.loads(p.read_text())
            grid[(r, s)] = (d[0] if isinstance(d, list) else d)

